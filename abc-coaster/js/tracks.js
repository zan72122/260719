/* =========================================================
 * tracks.js — アルファベット26文字の「形」データベース
 *
 * ride  : コースターが走る一筆書きレール (100x100 の箱, y は下向き)
 *         文字の骨格そのもの。O は宙返りループ、W は二段谷、
 *         Z は2回ヘアピン、G は行き止まりで跳ね返る。
 * struts: 走らない画数は「鉄骨」として描き、文字の見た目を完成させる
 * closed/counters: 閉じた輪 (穴) の位置 → ふうせんもじで膨らむ場所
 * leak  : 開いた文字の「すきま」の位置 → 空気が漏れる場所
 * ========================================================= */

const Tracks = (() => {

  function rainbow(i) { return `hsl(${(i / 26) * 330}, 82%, 55%)`; }

  // 楕円弧のサンプル点列 (角度は度, y下向き画面で a0→a1 に進む)
  function arcE(cx, cy, rx, ry, a0, a1, steps = 22) {
    const pts = [];
    for (let i = 0; i <= steps; i++) {
      const a = (a0 + (a1 - a0) * (i / steps)) * Math.PI / 180;
      pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
    }
    return pts;
  }

  const L = {}; // 文字データ本体

  /* ---------------- レール定義 ---------------- */

  L.A = { ride: [[2, 98], [50, 2], [98, 98]],
          struts: [[[26, 56], [74, 56]]] };

  L.B = { ride: [[2, 96], [14, 96], [14, 6],
                 ...arcE(14, 28, 30, 22, -90, 90),   // 上のこぶ
                 ...arcE(14, 73, 33, 23, -90, 90)],  // 下のこぶ
          struts: [] };

  L.C = { ride: arcE(52, 50, 42, 44, -55, -305, 30) }; // 右あきの大アーチ

  L.D = { ride: [[2, 96], [16, 96], [16, 4], ...arcE(16, 50, 54, 46, -90, 90)] };

  L.E = { ride: [[88, 8], [16, 8], [16, 92], [92, 92]],
          struts: [[[16, 50], [70, 50]]] };

  L.F = { ride: [[88, 8], [16, 8], [16, 94]],
          struts: [[[16, 50], [64, 50]]] };

  // G: 内側の棚が行き止まり → バンパーにぶつかって逆走して出る!
  L.G = { ride: [...arcE(52, 50, 42, 44, -55, -335, 30), [56, 66], [96, 66]],
          bumper: [58, 66] };

  L.H = { ride: [[14, 96], [14, 6], [14, 52], [76, 52], [76, 6], [76, 96]] };

  L.I = { ride: [[50, 4], [50, 96]],
          struts: [[[26, 4], [74, 4]], [[26, 96], [74, 96]]] };

  // J: フックで上向きに発射 → 次の文字までジャンプ!
  L.J = { ride: [[62, 4], [62, 62], ...arcE(40, 62, 22, 24, 0, 180)],
          struts: [[[40, 4], [84, 4]]],
          launch: true };

  L.K = { ride: [[86, 6], [20, 50], [88, 94]],
          struts: [[[12, 4], [12, 96]]] };

  L.L = { ride: [[16, 6], [16, 88], [92, 88]] };

  L.M = { ride: [[4, 96], [10, 8], [50, 78], [90, 8], [96, 96]] };

  L.N = { ride: [[8, 96], [12, 10], [80, 92], [84, 6]] };

  L.O = { ride: arcE(50, 50, 40, 44, 90, -270, 36) }; // 完全一回転ループ!

  L.P = { ride: [[16, 96], [16, 6], ...arcE(16, 29, 42, 23, -90, 90), [16, 96]] };

  L.Q = { ride: [...arcE(50, 46, 38, 40, 90, -270, 36), [64, 70], [94, 98]] };

  L.R = { ride: [[16, 96], [16, 6], ...arcE(16, 28, 42, 22, -90, 90), [88, 96]] };

  L.S = { ride: [[80, 14], [64, 4], [40, 4], [25, 15], [26, 31], [42, 43],
                 [62, 52], [75, 63], [75, 79], [60, 92], [36, 95], [19, 85]] };

  L.T = { ride: [[6, 10], [50, 10], [50, 94]],
          struts: [[[50, 10], [94, 10]]] };

  L.U = { ride: [[14, 8], [14, 58], ...arcE(50, 58, 36, 37, 180, 0), [86, 8]] }; // 谷底を通る

  L.V = { ride: [[6, 6], [50, 94], [94, 6]] };

  L.W = { ride: [[2, 6], [24, 94], [50, 30], [76, 94], [98, 6]] };

  L.X = { ride: [[6, 8], [92, 92]],
          struts: [[[92, 8], [6, 92]]] };

  L.Y = { ride: [[8, 6], [50, 48], [50, 94]],
          struts: [[[92, 6], [50, 48]]] };

  L.Z = { ride: [[8, 14], [88, 14], [16, 86], [94, 86]] };

  /* ---------------- ふうせんもじ用: 閉/開データ ---------------- */
  // counters: 閉じた輪 (穴) [cx, cy, rx, ry] — ここが風船になる
  // leak: 開いた文字のすきま [x, y, 向き(度)] — ここから空気が漏れる

  const topo = {
    A: { counters: [[50, 40, 11, 9]] },
    B: { counters: [[36, 28, 13, 10], [38, 72, 14, 11]] },
    D: { counters: [[42, 50, 18, 24]] },
    O: { counters: [[50, 50, 21, 25]] },
    P: { counters: [[38, 29, 13, 10]] },
    Q: { counters: [[50, 46, 19, 22]] },
    R: { counters: [[38, 28, 13, 10]] },

    C: { leak: [88, 50, 0] },
    E: { leak: [80, 50, 0] },
    F: { leak: [70, 75, 45] },
    G: { leak: [90, 48, 0] },
    H: { leak: [45, 24, -90] },
    I: { leak: [62, 50, 0] },
    J: { leak: [30, 30, 180] },
    K: { leak: [60, 50, 0] },
    L: { leak: [60, 40, 20] },
    M: { leak: [30, 65, 90] },
    N: { leak: [45, 65, 90] },
    S: { leak: [70, 28, 0] },
    T: { leak: [26, 50, 90] },
    U: { leak: [50, 18, -90] },
    V: { leak: [50, 22, -90] },
    W: { leak: [37, 20, -90] },
    X: { leak: [50, 24, -90] },
    Y: { leak: [50, 20, -90] },
    Z: { leak: [55, 50, 0] },
  };

  /* ---------------- さかさまサーカス用: 180°回転データ ---------------- */
  // flip: 180°回すと何に見えるか / distractor: クイズのもう1つの選択肢

  const circus = [
    // 回っても同じ「さかさまチャンピオン」
    { glyph: 'N', result: 'N', distractor: 'M' },
    { glyph: 'S', result: 'S', distractor: 'Z' },
    { glyph: 'Z', result: 'Z', distractor: 'S' },
    { glyph: 'O', result: 'O', distractor: 'Q' },
    { glyph: 'H', result: 'H', distractor: 'E' },
    { glyph: 'I', result: 'I', distractor: 'T' },
    { glyph: 'X', result: 'X', distractor: 'K' },
    // 回ると別人になる変身組
    { glyph: 'M', result: 'W', distractor: 'M' },
    { glyph: 'W', result: 'M', distractor: 'W' },
    { glyph: 'b', result: 'q', distractor: 'b' },
    { glyph: 'q', result: 'b', distractor: 'q' },
    { glyph: 'd', result: 'p', distractor: 'd' },
    { glyph: 'p', result: 'd', distractor: 'p' },
    { glyph: 'u', result: 'n', distractor: 'u' },
    { glyph: 'n', result: 'u', distractor: 'n' },
  ];

  /* ---------------- 仕上げ ---------------- */

  const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');
  ALPHABET.forEach((ch, i) => {
    L[ch].color = rainbow(i);
    L[ch].struts = L[ch].struts || [];
    L[ch].topo = topo[ch];
    L[ch].closed = !!(topo[ch] && topo[ch].counters);
  });

  return { letters: L, ALPHABET, circus, rainbow };
})();

window.Tracks = Tracks;
